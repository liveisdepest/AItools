-- ------------------------------------------------------------
-- 刷新冗余计数（发布/下线工具后重跑这一段即可）
-- ------------------------------------------------------------
UPDATE categories c
SET c.tool_count = (
  SELECT COUNT(*) FROM tools t
  WHERE t.category_id = c.id AND t.status = 'published'
);

UPDATE tags g
SET g.tool_count = (
  SELECT COUNT(*) FROM tool_tags tt
  JOIN tools t ON t.id = tt.tool_id AND t.status = 'published'
  WHERE tt.tag_id = g.id
);

-- 自检：应输出 8 个分类、60 个工具、32 个标签
SELECT
  (SELECT COUNT(*) FROM categories) AS categories,
  (SELECT COUNT(*) FROM tools WHERE status = 'published') AS tools,
  (SELECT COUNT(*) FROM tags) AS tags,
  (SELECT COUNT(*) FROM collections) AS collections;
